/**
 * Builds src/data/thirukkural.json — all 1330 Thirukkural couplets in a clean structure
 * the Thiruvalluvar scroll reads directly.
 *
 *   npm run build:kural                     # download the dataset
 *   npm run build:kural -- --source <dir>   # use a local thirukkural.json + detail.json
 *
 * Each entry:
 *   { number, section: { number, tamil, english }, chapter: { number, tamil, english },
 *     tamilLine1, tamilLine2, transliteration, translation, explanation,
 *     studentMeaning: { en, ta } | null }
 *
 * Sources:
 * - Verses, transliteration, G. U. Pope's English translation (1886) and the 1886 English
 *   explanations come from github.com/tk120404/thirukkural (Apache-2.0); their spelling is
 *   corrected and Pope's archaic words modernised (scripts/kuralCorrections.mjs). Its modern Tamil
 *   commentaries are left out because they are still under copyright.
 * - `studentMeaning` is written by the museum for the student favourites in
 *   src/data/thirukkural.js (null for the rest; the scroll then shows `explanation`).
 */
import { readFile, writeFile } from 'node:fs/promises';
import { assertVenbaLines, fixEnglish, KURAL_CORRECTIONS, modernizeEnglish } from './kuralCorrections.mjs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { studentFavourites } from '../src/data/thirukkural.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = resolve(ROOT, 'src/data/thirukkural.json');
const STRUCTURE_OUTPUT = resolve(ROOT, 'src/data/kuralStructure.js');
const DATASET_URL = 'https://raw.githubusercontent.com/tk120404/thirukkural/master';

const args = process.argv.slice(2);
const sourceDir = args.includes('--source') ? args[args.indexOf('--source') + 1] : null;

async function loadJson(name) {
  if (sourceDir) return JSON.parse(await readFile(resolve(sourceDir, name), 'utf8'));
  const response = await fetch(`${DATASET_URL}/${name}`);
  if (!response.ok) throw new Error(`Could not download ${name}: ${response.status}`);
  return response.json();
}

const [dataset, detail] = await Promise.all([loadJson('thirukkural.json'), loadJson('detail.json')]);

const sections = detail[0].section.detail.map((section) => ({
  number: section.number,
  tamil: section.name,
  english: section.translation,
  transliteration: section.transliteration,
  groups: section.chapterGroup.detail.map((group) => ({
    number: group.number,
    tamil: group.name,
    english: group.translation,
    chapters: group.chapters.detail.map((chapter) => ({
      number: chapter.number,
      tamil: chapter.name,
      english: fixEnglish(chapter.translation),
      transliteration: chapter.transliteration,
      start: chapter.start,
      end: chapter.end,
    })),
  })),
}));
const chapterOf = new Map();
for (const section of sections) {
  for (const group of section.groups) {
    for (const chapter of group.chapters) {
      for (let n = chapter.start; n <= chapter.end; n += 1) chapterOf.set(n, { section, chapter });
    }
  }
}
const meanings = new Map(studentFavourites.map((k) => [k.number, { en: k.meaning, ta: k.meaningTa }]));

const kurals = dataset.kural
  .sort((a, b) => a.Number - b.Number)
  .map((k) => {
    const { section, chapter } = chapterOf.get(k.Number);
    return {
      number: k.Number,
      section: { number: section.number, tamil: section.tamil, english: section.english },
      chapter: { number: chapter.number, tamil: chapter.tamil, english: chapter.english },
      tamilLine1: (KURAL_CORRECTIONS[k.Number]?.tamilLine1 ?? k.Line1).trim(),
      tamilLine2: (KURAL_CORRECTIONS[k.Number]?.tamilLine2 ?? k.Line2).trim(),
      transliteration: [k.transliteration1, k.transliteration2].filter(Boolean).map((line) => line.trim()).join('\n'),
      translation: modernizeEnglish(fixEnglish(k.couplet.trim(), { rejoinLines: true })),
      explanation: modernizeEnglish(fixEnglish(k.explanation.trim(), { rejoinLines: true })),
      studentMeaning: meanings.get(k.Number) ?? null,
    };
  });
if (kurals.length !== 1330) throw new Error(`Expected 1330 kurals, got ${kurals.length}`);
assertVenbaLines(kurals);

await writeFile(
  OUTPUT,
  `${JSON.stringify({
    source: 'Tamil verses, transliteration, G. U. Pope (1886) translation and 1886 English explanations via github.com/tk120404/thirukkural (Apache-2.0), with spelling corrected and modern vocabulary. studentMeaning written by the museum.',
    kurals,
  }, null, 1)}\n`,
);
await writeFile(
  STRUCTURE_OUTPUT,
  `// Generated by scripts/build-thirukkural.mjs — the three பால் (sections), their இயல் (groups), and 133 அதிகாரங்கள் (chapters).\nexport const kuralSections = ${JSON.stringify(sections, null, 2)};\n`,
);
console.log(`Wrote ${kurals.length} kurals (${meanings.size} with student meanings).`);
